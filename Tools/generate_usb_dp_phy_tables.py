#!/usr/bin/env python3
"""Generate only the public SM8450 combo-PHY constant tables, never code."""
import argparse
from pathlib import Path
import re

TABLES = (
    "sm8150_usb3_serdes_tbl", "sm8350_usb3_tx_tbl", "sm8350_usb3_rx_tbl",
    "sm8350_usb3_pcs_tbl", "sm8350_usb3_pcs_usb_tbl", "qmp_v4_dp_serdes_tbl",
    "qmp_v5_dp_tx_tbl", "qmp_v4_dp_serdes_tbl_rbr", "qmp_v4_dp_serdes_tbl_hbr",
    "qmp_v4_dp_serdes_tbl_hbr2", "qmp_v4_dp_serdes_tbl_hbr3",
)
REGS = (
    "QPHY_V4_PCS_SW_RESET", "QPHY_V4_PCS_START_CONTROL", "QPHY_V4_PCS_PCS_STATUS1",
    "QPHY_V4_PCS_POWER_DOWN_CONTROL", "QSERDES_V4_COM_RESETSM_CNTRL",
    "QSERDES_V4_COM_C_READY_STATUS", "QSERDES_V4_COM_CMN_STATUS",
    "QSERDES_V4_COM_BIAS_EN_CLKBUFLR_EN", "QSERDES_V4_TX_TX_POL_INV",
    "QSERDES_V4_TX_TX_DRV_LVL", "QSERDES_V4_TX_TX_EMP_POST1_LVL",
    "QSERDES_V4_TX_HIGHZ_DRVR_EN", "QSERDES_V4_TX_TRANSCEIVER_BIAS_EN",
)


def generate(root):
    phy = root / "drivers/phy/qualcomm"
    constants = {}
    for header in sorted(phy.glob("phy-qcom-qmp*.h")):
        for name, literal in re.findall(
                r"^#define\s+(\w+)\s+(0x[0-9a-fA-F]+)\s*$",
                header.read_text(), re.MULTILINE):
            value = int(literal, 16)
            if name in constants and constants[name] != value:
                raise ValueError(f"conflicting definition: {name}")
            constants[name] = value
    source = (phy / "phy-qcom-qmp-combo.c").read_text()
    lines = [
        "/* Generated by Tools/generate_usb_dp_phy_tables.py from Linux",
        " * phy-qcom-qmp-combo.c sm8350_usb3dpphy_cfg (also SM8450).",
        " * Copyright (c) 2017-2021, The Linux Foundation.",
        " * SPDX-License-Identifier: GPL-2.0-only */", "#pragma once",
        "typedef struct { UINT16 Offset; UINT8 Value, LaneMask; } CR_PHY_REG;",
    ]
    for reg in REGS:
        lines.append(f"#define {reg} 0x{constants[reg]:03X}U")
    for name in TABLES:
        pattern = (r"static const struct qmp_phy_init_tbl " + re.escape(name) +
                   r"\[\] = \{(.*?)\n\};")
        matches = re.findall(pattern, source, re.DOTALL)
        if len(matches) != 1:
            raise ValueError(f"table missing or ambiguous: {name}")
        body = re.sub(r"/\*.*?\*/", "", matches[0], flags=re.DOTALL)
        body = re.sub(r"//[^\n]*", "", body)
        lines.append(f"STATIC CONST CR_PHY_REG {name}[] = {{")
        for row in body.splitlines():
            if not row.strip():
                continue
            entry = re.fullmatch(
                r"\s*QMP_PHY_INIT_CFG(_LANE)?\(\s*(\w+),\s*(0x[\da-fA-F]+|\d+)"
                r"(?:,\s*(\d+))?\s*\),\s*", row)
            if not entry:
                raise ValueError(f"unrecognized table entry: {row}")
            lane, reg, literal, mask = entry.groups()
            if bool(lane) != bool(mask):
                raise ValueError(f"invalid lane entry: {row}")
            value = int(literal, 0)
            if constants[reg] >= 0x400 or value > 255:
                raise ValueError(f"out of range: {row}")
            lines.append(f"  {{0x{constants[reg]:03X}, 0x{value:02X}, {mask or '3'}}}, /* {reg} */")
        lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("linux", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate(args.linux)
    if args.check:
        if args.output.read_text() != expected:
            raise SystemExit("combo-PHY tables differ from public Linux reference")
    else:
        args.output.write_text(expected)


if __name__ == "__main__":
    main()
